interface TariffCard {
  code: LocalTariffCode;
  url: string | null;
  /** Dominio que se muestra junto al botón (sin `www.`), para saber adónde lleva el enlace. */
  domain: string | null;
}

/** Accesos internos relacionados con las tarifas. */
const QUICK_LINKS = [
  { route: '/charges', key: 'localTariffs.quick.charges' },
  { route: '/demurrage', key: 'localTariffs.quick.demurrage' },
  { route: '/faq', key: 'localTariffs.quick.faq' },
] as const;

/** Solo enlaces https absolutos: cualquier otro valor se trata como no configurado. */
function safeUrl(link: ExternalLink | undefined): string | null {
  if (!link?.configured || !link.url) return null;
  try {
    return new URL(link.url).protocol === 'https:' ? link.url : null;
  } catch {
    return null;
  }
}

/**
 * Tarifas locales: acceso a los tarifarios oficiales de Hapag-Lloyd (Inland Chile, Demurrage/Detention de
 * Latinoamérica y recargos locales). El portal no aloja las tarifas: cada tarjeta abre el sitio oficial en una
 * pestaña nueva (`rel="noopener noreferrer"`) y lo avisa en el nombre accesible del enlace. Un tarifario sin URL
 * configurada se muestra como no disponible, sin enlace.
 */
@Component({
  selector: 'app-local-tariffs',
  standalone: true,
  changeDetection: ChangeDetectionStrategy.OnPush,
  imports: [RouterLink, TranslocoPipe, StateMessageComponent],
  templateUrl: './local-tariffs.html',
  styleUrl: './local-tariffs.scss',
})
export class LocalTariffsComponent {
  readonly links = inject(PortalLinkService);

  readonly icons = ICONS;
  readonly order = TARIFF_ORDER;
  readonly keys = TARIFF_KEYS;
  readonly quickLinks = QUICK_LINKS;

  readonly state = this.links.externalLinksState;

  readonly cards = computed<TariffCard[]>(() => {
    const tariffs = this.links.externalLinks()?.localTariffs ?? [];
    return TARIFF_ORDER.map((code) => {
      const url = safeUrl(tariffs.find((t) => t.code === code));
      return { code, url, domain: url ? new URL(url).hostname.replace(/^www\./, '') : null };
    });
  });

  constructor() {
    // Se piden al entrar y otra vez si cambia la sesión o el país (el servicio los descarta).
    effect(() => {
      if (this.state() === 'idle') untracked(() => this.links.loadExternalLinks());
    });
  }

  retry(): void {
    this.links.loadExternalLinks();
  }
}
